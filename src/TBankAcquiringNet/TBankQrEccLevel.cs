namespace TBankAcquiringNet;

/// <summary>
/// Уровень коррекции ошибок QR-кода.
/// </summary>
/// <remarks>
/// Чем выше уровень, тем больше повреждений символа переживёт код — и тем крупнее он получится
/// при той же длине ссылки. Для платёжных ссылок на экране подходит <see cref="M"/>: экран не
/// пачкается и не выцветает, а запас в 15% покрывает блики и дешёвые камеры.
/// </remarks>
public enum TBankQrEccLevel
{
    /// <summary>Восстанавливает около 7% кодовых слов.</summary>
    L = 0,

    /// <summary>Восстанавливает около 15% кодовых слов. Значение по умолчанию.</summary>
    M = 1,

    /// <summary>Восстанавливает около 25% кодовых слов.</summary>
    Q = 2,

    /// <summary>Восстанавливает около 30% кодовых слов.</summary>
    H = 3
}
