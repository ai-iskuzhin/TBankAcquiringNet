    [Theory]
    [MemberData(nameof(Golden))]
    public void Matches_the_reference_implementation(
        string name,
        string text,
        TBankQrEccLevel ecc,
        int expectedVersion,
        int expectedMask,
        string[] expectedRows)
    {
        _ = name;

        var code = TBankQrCode.Encode(text, ecc);

        Assert.Equal(expectedVersion, code.Version);
        Assert.Equal(expectedMask, code.Mask);
        Assert.Equal(expectedRows, Render(code));
    }

    private static string[] Render(TBankQrCode code)
    {
        var rows = new string[code.Size];
        for (var row = 0; row < code.Size; row++)
        {
            var line = new StringBuilder(code.Size);
            for (var col = 0; col < code.Size; col++)
            {
                line.Append(code.Modules[row, col] ? '1' : '0');
            }

            rows[row] = line.ToString();
        }

        return rows;
    }
